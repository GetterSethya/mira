import ts from "typescript"
import { describe, expect, it } from "vitest"

import type { ApiCollectionSchema } from "@gettersethya/mira-client"

import {
  generateCollectionFile,
  pascalCase,
  resolveSubset
} from "../src/codegen.js"

const users: ApiCollectionSchema = {
  name: "users",
  kind: "auth",
  required: ["email", "password", "displayName"],
  indexes: [{ fields: ["email"], unique: true }],
  fields: {
    id: { type: "string", "x-system": true, "x-generated": true },
    seqId: { type: "integer", "x-kind": "seqId", "x-system": true, "x-hidden": true, "x-generated": true },
    email: { type: "string", format: "email", "x-system": true },
    password: { type: "string", "x-system": true, "x-hidden": true, "x-kind": "password" },
    emailVerified: { type: "boolean", "x-system": true, default: false },
    displayName: { type: "string", maxLength: 100 },
    created: { type: "string", "x-system": true, "x-generated": true },
    updated: { type: "string", "x-system": true, "x-generated": true }
  }
}

const posts: ApiCollectionSchema = {
  name: "posts",
  kind: "base",
  required: ["title", "authorId"],
  indexes: [{ fields: ["published"], unique: false }],
  fields: {
    id: { type: "string", "x-system": true, "x-generated": true },
    seqId: { type: "integer", "x-kind": "seqId", "x-system": true, "x-hidden": true, "x-generated": true },
    title: { type: "string", maxLength: 200 },
    body: { type: "string" },
    published: { type: "boolean", default: false },
    authorId: { type: "string", "x-kind": "relation", "x-collection": "users", "x-field": "id" },
    cover: { type: "string", "x-kind": "file", "x-maxSize": 5242880, "x-mimeTypes": ["image/*"] },
    created: { type: "string", "x-system": true, "x-generated": true },
    updated: { type: "string", "x-system": true, "x-generated": true }
  }
}

const publishedPosts: ApiCollectionSchema = {
  name: "published_posts",
  kind: "view",
  viewQuery: "SELECT p.id, CAST(ROW_NUMBER() OVER (ORDER BY p.seqId) AS INTEGER) AS seqId, p.title FROM posts p WHERE p.published = 1",
  fields: {
    id: { type: "string", "x-view-only": true },
    seqId: { type: "integer", "x-kind": "seqId", "x-view-only": true },
    title: { type: "string", "x-view-only": true }
  }
}

const accounts: ApiCollectionSchema = {
  name: "accounts",
  kind: "base",
  required: ["ownerId"],
  fields: {
    id: { type: "string", "x-system": true, "x-generated": true },
    seqId: { type: "integer", "x-kind": "seqId", "x-system": true, "x-hidden": true, "x-generated": true },
    role: { type: "string", "x-kind": "literalText", "x-literal": ["admin", "member"], default: "member" },
    nickname: { type: "string", "x-hidden": true },
    ownerId: { type: "string", "x-kind": "relation", "x-collection": "users", "x-field": "email" },
    quota: { type: "integer", minimum: 0, maximum: 100, default: 10 },
    created: { type: "string", "x-system": true, "x-generated": true },
    updated: { type: "string", "x-system": true, "x-generated": true }
  }
}

const all = [users, posts, publishedPosts]

function generate(
  schemas: ReadonlyArray<ApiCollectionSchema>,
  include?: ReadonlyArray<string>
): string {
  return generateCollectionFile(
    schemas,
    include === undefined
      ? { generatedAt: "2026-01-01T00:00:00.000Z" }
      : { generatedAt: "2026-01-01T00:00:00.000Z", include }
  )
}

function expectParses(source: string): void {
  const result = ts.transpileModule(source, {
    reportDiagnostics: true,
    compilerOptions: {
      module: ts.ModuleKind.ESNext,
      target: ts.ScriptTarget.ES2022
    }
  })
  const diagnostics = (result.diagnostics ?? []).map((diagnostic) =>
    ts.flattenDiagnosticMessageText(diagnostic.messageText, "\n")
  )
  expect(diagnostics).toEqual([])
}

describe("pascalCase", () => {
  it("converts snake_case, kebab-case, and camelCase names", () => {
    expect(pascalCase("posts")).toBe("Posts")
    expect(pascalCase("published_posts")).toBe("PublishedPosts")
    expect(pascalCase("user-profiles")).toBe("UserProfiles")
    expect(pascalCase("2fa_codes")).toBe("_2faCodes")
  })
})

describe("generateCollectionFile", () => {
  it("writes the header, imports, and a deterministic timestamp", () => {
    const output = generate(all)

    expect(output).toContain("// AUTO-GENERATED by the Mira dashboard — do not edit by hand.")
    expect(output).toContain("// Source: GET /api/_schema (generated 2026-01-01T00:00:00.000Z)")
    expect(output).toContain("// Client-only: server-side rules and indexes are not included.")
    expect(output).toContain('} from "@gettersethya/mira-client"')
    expect(output).toContain("type InferRecord")
    expect(output).toContain("type CreateInput")
    expect(output).toContain("type UpdateInput")
  })

  it("imports only the builders and types it uses", () => {
    const viewOnly = generate([publishedPosts])

    expect(viewOnly).toContain("ViewCollection,")
    expect(viewOnly).toContain("  Field,")
    expect(viewOnly).toContain("type InferRecord")
    expect(viewOnly).not.toContain("AuthCollection")
    expect(viewOnly).not.toContain("BaseCollection")
    expect(viewOnly).not.toContain("CreateInput")
    expect(viewOnly).not.toContain("UpdateInput")

    const empty = generate([])

    expect(empty).not.toContain("@gettersethya/mira-client")
    expect(empty).toContain("export const collections = {}")
  })

  it("renders auth collections without system fields", () => {
    const output = generate(all)

    expect(output).toContain('export const Users = AuthCollection.define("users", {')
    expect(output).toContain("displayName: Field.text({ maxLength: 100 }),")
    expect(output).not.toContain("email: Field.email")
    expect(output).not.toContain("password: Field.text")
    expect(output).not.toContain("emailVerified: Field.boolean")
    expect(output).toContain("export type UsersRecord = InferRecord<typeof Users.fields>")
    expect(output).toContain('export type UsersCreate = CreateInput<typeof Users.fields, "auth">')
    expect(output).toContain('export type UsersUpdate = UpdateInput<typeof Users.fields, "auth">')
  })

  it("renders base fields, constraints, hidden fields, relations, and files", () => {
    const output = generate([users, posts, accounts])

    expect(output).toContain('export const Posts = BaseCollection.define("posts", {')
    expect(output).toContain("title: Field.text({ maxLength: 200 }),")
    expect(output).toContain("body: Field.text({ required: false }),")
    expect(output).toContain("published: Field.boolean({ default: false, required: false }),")
    expect(output).toContain("authorId: Field.relation(Users),")
    expect(output).toContain(
      'cover: Field.file({ maxSize: 5242880, mimeTypes: ["image/*"], required: false }),'
    )
    expect(output).toContain(
      'role: Field.literalText({ literal: ["admin", "member"] as const, default: "member", required: false }),'
    )
    expect(output).toContain("nickname: Field.text({ hidden: true, required: false }),")
    expect(output).toContain('ownerId: Field.relation(Users, { field: "email" }),')
    expect(output).toContain(
      "quota: Field.integer({ minimum: 0, maximum: 100, default: 10, required: false }),"
    )
    expect(output).toContain('export type PostsCreate = CreateInput<typeof Posts.fields, "base">')
    expect(output).toContain('export type PostsUpdate = UpdateInput<typeof Posts.fields, "base">')
  })

  it("renders view collections with view-only fields and no write aliases", () => {
    const output = generate(all)
    const view = output.slice(output.indexOf("export const PublishedPosts"))

    expect(view).toContain("export const PublishedPosts = ViewCollection.define(")
    expect(view).toContain('"published_posts",')
    expect(view).toContain("id: Field.text().view(),")
    expect(view).toContain("seqId: Field.integer().view(),")
    expect(view).toContain("title: Field.text().view(),")
    expect(view).toContain("export type PublishedPostsRecord = InferRecord<typeof PublishedPosts.fields>")
    expect(view).not.toContain("PublishedPostsCreate")
    expect(view).not.toContain("PublishedPostsUpdate")
  })

  it("escapes backticks and interpolation in view SQL", () => {
    const tricky: ApiCollectionSchema = {
      name: "billing_view",
      kind: "view",
      viewQuery: "SELECT `total` FROM billing WHERE note = '${notAParam}'",
      fields: {
        id: { type: "string", "x-view-only": true },
        seqId: { type: "integer", "x-kind": "seqId", "x-view-only": true },
        total: { type: "number", "x-view-only": true }
      }
    }

    const output = generate([tricky])

    expect(output).toContain("\\`total\\`")
    expect(output).toContain("\\${notAParam}")
    expectParses(output)
  })

  it("orders relation targets before their referrers", () => {
    const output = generate([posts, users])

    expect(output.indexOf("export const Users")).toBeLessThan(output.indexOf("export const Posts"))
  })

  it("falls back to input order and warns on cyclic relations", () => {
    const a: ApiCollectionSchema = {
      name: "a",
      kind: "base",
      fields: {
        id: { type: "string", "x-system": true, "x-generated": true },
        bId: { type: "string", "x-kind": "relation", "x-collection": "b", "x-field": "id" }
      }
    }
    const b: ApiCollectionSchema = {
      name: "b",
      kind: "base",
      fields: {
        id: { type: "string", "x-system": true, "x-generated": true },
        aId: { type: "string", "x-kind": "relation", "x-collection": "a", "x-field": "id" }
      }
    }

    const output = generate([a, b])

    expect(output).toContain("// WARNING: cyclic relations — reorder these defs manually")
    expect(output.indexOf("export const A")).toBeLessThan(output.indexOf("export const B"))
    expect(output).toContain("bId: Field.relation(B, { required: false }),")
    expect(output).toContain("aId: Field.relation(A, { required: false }),")
    expectParses(output)
  })

  it("emits a text fallback for missing relation targets", () => {
    const output = generate([posts], ["posts"])

    expect(output).toContain('authorId: Field.text(), // relation target "users" was not found')
  })

  it("honours the include option", () => {
    const output = generate([users, posts, publishedPosts], ["users", "posts"])

    expect(output).toContain("export const Users")
    expect(output).toContain("export const Posts")
    expect(output).not.toContain("export const PublishedPosts")
    expect(output).toContain('"users": Users,')
    expect(output).toContain('"posts": Posts,')
    expect(output).not.toContain('"published_posts": PublishedPosts,')
  })

  it("renders the collections map in emitted order", () => {
    const output = generate([publishedPosts, posts, users])
    const map = output.slice(output.indexOf("export const collections"))

    // Input order was view-first, but posts pulls users ahead of it.
    expect(map.indexOf('"published_posts": PublishedPosts,')).toBeLessThan(
      map.indexOf('"users": Users,')
    )
    expect(map.indexOf('"users": Users,')).toBeLessThan(map.indexOf('"posts": Posts,'))
  })

  it("produces parseable TypeScript for every generated output", () => {
    const outputs = [
      generate(all),
      generate([users, posts, accounts]),
      generate([posts], ["posts"]),
      generate(all, ["users", "posts"]),
      generate([])
    ]

    for (const output of outputs) expectParses(output)
  })
})

describe("resolveSubset", () => {
  it("returns the root plus its transitive relation targets, dependency-first", () => {
    const subset = resolveSubset([publishedPosts, posts, users], "posts")

    expect(subset.map((schema) => schema.name)).toEqual(["users", "posts"])
  })

  it("walks nested relations", () => {
    const subset = resolveSubset([accounts, posts, users], "accounts")

    expect(subset.map((schema) => schema.name)).toEqual(["users", "accounts"])
  })

  it("returns a collection without relations on its own", () => {
    const subset = resolveSubset(all, "published_posts")

    expect(subset.map((schema) => schema.name)).toEqual(["published_posts"])
  })

  it("returns an empty array for an unknown root", () => {
    expect(resolveSubset(all, "missing")).toEqual([])
  })
})
