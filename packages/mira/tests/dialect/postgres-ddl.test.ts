import { describe, it } from "@effect/vitest"
import { Effect } from "effect"
import { expect } from "vitest"

import type { TranslatePlanContext } from "@/dialect/dialect.js"
import { postgresDdlSql } from "@/dialect/dialect-postgres.js"
import type { ColumnDef, MigrationStep } from "@/migrator/types.js"

const column = (
  name: string,
  type: ColumnDef["type"],
  overrides: Partial<ColumnDef> = {}
): ColumnDef => ({
  name,
  type,
  nullable: false,
  ...overrides
})

const seqId = column("seqId", "integer", {
  primaryKey: true,
  autoIncrement: true,
  xSystem: true
})
const id = column("id", "text", { unique: true, xSystem: true })
const title = column("title", "text")

const context = (): TranslatePlanContext => ({
  tables: new Map(),
  views: new Map(),
  readonlyQuery: () => Effect.succeed([])
})

const plan = (steps: ReadonlyArray<MigrationStep>, ctx = context()) =>
  postgresDdlSql.translatePlan(steps, ctx)

const failureDetail = (steps: ReadonlyArray<MigrationStep>, ctx = context()) =>
  plan(steps, ctx).pipe(
    Effect.catchTag("UnsupportedMigrationStepError", (error) => Effect.succeed(error.detail)),
    Effect.orDie
  )

describe("postgresDdlSql type mapping and identity", () => {
  it("maps the four column types", () => {
    expect(postgresDdlSql.nativeType(column("t", "text"))).toBe("TEXT")
    expect(postgresDdlSql.nativeType(column("t", "integer"))).toBe("INTEGER")
    expect(postgresDdlSql.nativeType(column("t", "real"))).toBe("DOUBLE PRECISION")
    expect(postgresDdlSql.nativeType(column("t", "boolean"))).toBe("BOOLEAN")
    expect(postgresDdlSql.storesBooleanAsInteger).toBe(false)
  })

  it.effect("renders seqId as a BIGINT identity primary key", () =>
    Effect.gen(function* () {
      const { statements } = yield* plan([
        {
          kind: "createTable",
          table: "posts",
          columns: [seqId, id, title]
        }
      ])
      expect(statements[0]).toContain(
        '"seqId" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
      )
    }))

  it.effect("renders an identity column with UNIQUE when it is not the primary key", () =>
    Effect.gen(function* () {
      const { statements } = yield* plan([
        {
          kind: "createTable",
          table: "posts",
          columns: [
            column("seqId", "integer", {
              autoIncrement: true,
              unique: true,
              xSystem: true
            })
          ]
        }
      ])
      expect(statements[0]).toContain(
        '"seqId" BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE'
      )
    }))
})

describe("postgresDdlSql step templates", () => {
  it("renders the non-view step forms", () => {
    expect(postgresDdlSql.translate({ kind: "dropTable", table: "t" })).toEqual([
      'DROP TABLE IF EXISTS "t"'
    ])
    expect(
      postgresDdlSql.translate({ kind: "renameTable", from: "a", to: "b" })
    ).toEqual(['ALTER TABLE "a" RENAME TO "b"'])
    expect(
      postgresDdlSql.translate({ kind: "dropColumn", table: "t", column: "c" })
    ).toEqual(['ALTER TABLE "t" DROP COLUMN "c"'])
    expect(
      postgresDdlSql.translate({
        kind: "renameColumn",
        table: "t",
        from: "a",
        to: "b"
      })
    ).toEqual(['ALTER TABLE "t" RENAME COLUMN "a" TO "b"'])
    expect(
      postgresDdlSql.translate({
        kind: "createSystemTable",
        table: "_collections",
        columns: [column("name", "text", { primaryKey: true })]
      })[0]
    ).toContain('CREATE TABLE IF NOT EXISTS "_collections"')
    expect(
      postgresDdlSql.translate({
        kind: "createView",
        view: "v",
        query: "SELECT 1"
      })
    ).toEqual(['CREATE VIEW "v" AS SELECT 1'])
    expect(postgresDdlSql.translate({ kind: "dropView", view: "v" })).toEqual([
      'DROP VIEW IF EXISTS "v"'
    ])
  })

  it("renders create and drop index with the same derived name", () => {
    const create = postgresDdlSql.translate({
      kind: "createIndex",
      table: "todos",
      fields: ["category"],
      unique: false
    })
    const drop = postgresDdlSql.translate({
      kind: "dropIndex",
      table: "todos",
      fields: ["category"],
      unique: false
    })
    expect(create).toEqual([
      'CREATE INDEX "idx_todos_category" ON "todos" ("category")'
    ])
    expect(drop).toEqual(['DROP INDEX IF EXISTS "idx_todos_category"'])
  })
})

describe("postgresDdlSql defaults", () => {
  it.effect("renders boolean, integer, and text synthetic defaults on ADD COLUMN", () =>
    Effect.gen(function* () {
      const { statements } = yield* plan([
        {
          kind: "addColumn",
          table: "t",
          column: column("active", "boolean")
        },
        {
          kind: "addColumn",
          table: "t",
          column: column("count", "integer")
        },
        {
          kind: "addColumn",
          table: "t",
          column: column("label", "text")
        }
      ])
      expect(statements[0]).toContain('"active" BOOLEAN NOT NULL DEFAULT FALSE')
      expect(statements[1]).toContain('"count" INTEGER NOT NULL DEFAULT 0')
      expect(statements[2]).toContain('"label" TEXT NOT NULL DEFAULT \'\'')
    }))

  it.effect("coerces numeric boolean defaults in CREATE TABLE", () =>
    Effect.gen(function* () {
      const { statements } = yield* plan([
        {
          kind: "createTable",
          table: "t",
          columns: [
            column("a", "boolean", { default: 0 }),
            column("b", "boolean", { default: 1 }),
            column("c", "boolean", { default: "0" }),
            column("d", "boolean", { default: "1" })
          ]
        }
      ])
      expect(statements[0]).toContain('"a" BOOLEAN NOT NULL DEFAULT FALSE')
      expect(statements[0]).toContain('"b" BOOLEAN NOT NULL DEFAULT TRUE')
      expect(statements[0]).toContain('"c" BOOLEAN NOT NULL DEFAULT FALSE')
      expect(statements[0]).toContain('"d" BOOLEAN NOT NULL DEFAULT TRUE')
    }))

  it.effect("rejects a null default on a NOT NULL column", () =>
    Effect.gen(function* () {
      const detail = yield* failureDetail([
        {
          kind: "createTable",
          table: "t",
          columns: [column("a", "text", { default: null })]
        }
      ])
      expect(detail).toContain('default for "t"."a" is not valid for type text: null')
    }))

  it.effect("rejects a fractional integer default", () =>
    Effect.gen(function* () {
      const detail = yield* failureDetail([
        {
          kind: "createTable",
          table: "t",
          columns: [column("a", "integer", { default: 1.5 })]
        }
      ])
      expect(detail).toContain('default for "t"."a" is not valid for type integer: 1.5')
    }))

  it.effect("rejects an out-of-range integer default", () =>
    Effect.gen(function* () {
      const detail = yield* failureDetail([
        {
          kind: "createTable",
          table: "t",
          columns: [column("a", "integer", { default: 3000000000 })]
        }
      ])
      expect(detail).toContain(
        'default for "t"."a" is out of range for type integer: 3000000000'
      )
    }))

  it.effect("accepts the signed 32-bit integer bounds", () =>
    Effect.gen(function* () {
      const { statements } = yield* plan([
        {
          kind: "createTable",
          table: "t",
          columns: [
            column("max", "integer", { default: 2147483647 }),
            column("min", "integer", { default: -2147483648 })
          ]
        }
      ])
      expect(statements[0]).toContain('"max" INTEGER NOT NULL DEFAULT 2147483647')
      expect(statements[0]).toContain('"min" INTEGER NOT NULL DEFAULT -2147483648')
    }))

  it.effect("rejects a non-primitive default", () =>
    Effect.gen(function* () {
      const detail = yield* failureDetail([
        {
          kind: "createTable",
          table: "t",
          columns: [column("a", "text", { default: { bad: true } })]
        }
      ])
      expect(detail).toContain('default for "t"."a" is not valid for type text: {"bad":true}')
    }))
})

describe("postgresDdlSql ALTER COLUMN", () => {
  it.effect("drops the default before a type change and restores an unchanged default", () =>
    Effect.gen(function* () {
      const { statements } = yield* plan([
        {
          kind: "alterColumn",
          table: "t",
          from: column("n", "integer", { default: 0 }),
          to: column("n", "real", { default: 0 })
        }
      ])
      expect(statements).toEqual([
        'ALTER TABLE "t" ALTER COLUMN "n" DROP DEFAULT',
        'ALTER TABLE "t" ALTER COLUMN "n" TYPE DOUBLE PRECISION USING "n"::double precision',
        'ALTER TABLE "t" ALTER COLUMN "n" SET DEFAULT 0'
      ])
    }))

  it.effect("drops a synthetic default before a type change even when the schema has no default", () =>
    Effect.gen(function* () {
      const { statements } = yield* plan([
        {
          kind: "alterColumn",
          table: "t",
          from: column("n", "text"),
          to: column("n", "integer")
        }
      ])
      expect(statements[0]).toBe('ALTER TABLE "t" ALTER COLUMN "n" DROP DEFAULT')
      expect(statements[1]).toContain(
        'ALTER TABLE "t" ALTER COLUMN "n" TYPE INTEGER USING "n"::integer'
      )
      expect(statements).toHaveLength(2)
    }))

  it.effect("uses coerced boolean defaults in SET DEFAULT and the backfill", () =>
    Effect.gen(function* () {
      const { statements } = yield* plan([
        {
          kind: "alterColumn",
          table: "t",
          from: column("active", "boolean", { nullable: true }),
          to: column("active", "boolean", { nullable: false, default: 0 })
        }
      ])
      expect(statements).toEqual([
        'ALTER TABLE "t" ALTER COLUMN "active" SET DEFAULT FALSE',
        'UPDATE "t" SET "active" = FALSE WHERE "active" IS NULL',
        'ALTER TABLE "t" ALTER COLUMN "active" SET NOT NULL'
      ])
    }))

  it.effect("drops and sets defaults on the default-only path", () =>
    Effect.gen(function* () {
      const drop = yield* plan([
        {
          kind: "alterColumn",
          table: "t",
          from: column("a", "text", { default: "x" }),
          to: column("a", "text")
        }
      ])
      expect(drop.statements).toEqual(['ALTER TABLE "t" ALTER COLUMN "a" DROP DEFAULT'])

      const set = yield* plan([
        {
          kind: "alterColumn",
          table: "t",
          from: column("a", "text"),
          to: column("a", "text", { default: "x" })
        }
      ])
      expect(set.statements).toEqual(['ALTER TABLE "t" ALTER COLUMN "a" SET DEFAULT \'x\''])
    }))

  it.effect("drops NOT NULL when the column becomes nullable", () =>
    Effect.gen(function* () {
      const { statements } = yield* plan([
        {
          kind: "alterColumn",
          table: "t",
          from: column("a", "text"),
          to: column("a", "text", { nullable: true })
        }
      ])
      expect(statements).toEqual(['ALTER TABLE "t" ALTER COLUMN "a" DROP NOT NULL'])
    }))

  it.effect("drops a type change into the USING expression table", () =>
    Effect.gen(function* () {
      const cases: ReadonlyArray<readonly [ColumnDef["type"], ColumnDef["type"], string]> = [
        ["text", "integer", '"c"::integer'],
        ["text", "real", '"c"::double precision'],
        ["text", "boolean", '"c"::boolean'],
        ["integer", "real", '"c"::double precision'],
        ["integer", "boolean", '("c" <> 0)'],
        ["integer", "text", '"c"::text'],
        ["real", "integer", 'trunc("c")::integer'],
        ["real", "boolean", '("c" <> 0)'],
        ["real", "text", '"c"::text'],
        ["boolean", "integer", '"c"::integer'],
        ["boolean", "real", '("c"::integer)::double precision'],
        ["boolean", "text", '"c"::text']
      ]

      for (const [from, to, expected] of cases) {
        const { statements } = yield* plan([
          {
            kind: "alterColumn",
            table: "t",
            from: column("c", from),
            to: column("c", to)
          }
        ])
        expect(statements[1]).toContain(`USING ${expected}`)
      }
    }))

  it.effect("rejects a no-op alterColumn", () =>
    Effect.gen(function* () {
      const detail = yield* failureDetail([
        {
          kind: "alterColumn",
          table: "t",
          from: column("a", "text"),
          to: column("a", "text")
        }
      ])
      expect(detail).toBe('alterColumn "t"."a" has no changes')
    }))

  it.effect("rejects an identity alteration", () =>
    Effect.gen(function* () {
      const detail = yield* failureDetail([
        {
          kind: "alterColumn",
          table: "posts",
          from: seqId,
          to: { ...seqId, type: "real" }
        }
      ])
      expect(detail).toBe('changing identity column "posts"."seqId" is not supported')
    }))
})

describe("postgresDdlSql identifier limits", () => {
  it("leaves a short index name unchanged", () => {
    expect(postgresDdlSql.indexName("todos", ["category"])).toBe(
      "idx_todos_category"
    )
  })

  it("hashes long index names without collisions", () => {
    const first = postgresDdlSql.indexName(`idx_${"a".repeat(60)}_x`, [])
    const second = postgresDdlSql.indexName(`idx_${"a".repeat(60)}_y`, [])
    expect(new TextEncoder().encode(first).length).toBeLessThanOrEqual(63)
    expect(new TextEncoder().encode(second).length).toBeLessThanOrEqual(63)
    expect(first).not.toBe(second)
    expect(first.startsWith("idx_")).toBe(true)
  })

  it("truncates multi-byte names on a code-point boundary", () => {
    const name = postgresDdlSql.indexName(`idx_${"é".repeat(40)}`, [])
    expect(new TextEncoder().encode(name).length).toBeLessThanOrEqual(63)
    expect(name).not.toContain("\uFFFD")
  })

  it("uses the same truncated name for create and drop", () => {
    const table = "t".repeat(40)
    const fields = ["é".repeat(30)]
    const create = postgresDdlSql.translate({
      kind: "createIndex",
      table,
      fields,
      unique: false
    })[0]
    const drop = postgresDdlSql.translate({
      kind: "dropIndex",
      table,
      fields,
      unique: false
    })[0]
    const name = postgresDdlSql.indexName(table, fields)
    expect(create).toContain(`"${name}"`)
    expect(drop).toContain(`"${name}"`)
  })

  it.effect("rejects an overlong table name", () =>
    Effect.gen(function* () {
      const detail = yield* failureDetail([
        { kind: "dropTable", table: "t".repeat(64) }
      ])
      expect(detail).toContain("PostgreSQL identifiers must be at most 63 bytes")
    }))

  it.effect("rejects an overlong view name in a step", () =>
    Effect.gen(function* () {
      const detail = yield* failureDetail([
        { kind: "dropView", view: "v".repeat(64) }
      ])
      expect(detail).toContain("PostgreSQL identifiers must be at most 63 bytes")
    }))
})
